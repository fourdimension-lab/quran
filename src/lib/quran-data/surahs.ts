export function getSurahByNumber(num: number): Surah | undefined {
  return SURAHS_DATA.find((s) => s.number === num);
}

export function searchSurahs(query: string): Surah[] {
  if (!query) return SURAHS_DATA;
  const q = query.toLowerCase().trim();
  return SURAHS_DATA.filter((s) => 
    s.number.toString() === q ||
    s.name_en.toLowerCase().includes(q) ||
    s.name_transliteration.toLowerCase().includes(q) ||
    s.name_bn.includes(q) ||
    s.translation_en.toLowerCase().includes(q) ||
    s.translation_bn.includes(q) ||
    s.name_ar.includes(q)
  );
}
